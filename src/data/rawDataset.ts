// Generator to produce the full authentic dataset based on the distribution
export function parseCsvDataset(csvContent: string): RawComponentRecord[] {
  const lines = csvContent.trim().split(/\r?\n/);
  if (lines.length < 2) return [];

  const headers = lines[0].split(',').map(h => h.trim());
  const records: RawComponentRecord[] = [];

  for (let i = 1; i < lines.length; i++) {
    const line = lines[i].trim();
    if (!line) continue;
    const parts = line.split(',').map(p => p.trim());
    if (parts.length < 7) continue;

    const record: RawComponentRecord = {
      Component_ID: parts[0],
      Lot_ID: parts[1],
      Value_0h: parseFloat(parts[2]),
      Value_24h: parseFloat(parts[3]),
      Value_96h: parseFloat(parts[4]),
      Value_168h: parseFloat(parts[5]),
      Drift_0_24h: parts[6] !== undefined ? parseFloat(parts[6]) : (parseFloat(parts[3]) - parseFloat(parts[2])) / 24,
      Lot_Deviation_24h: parts[7] !== undefined ? parseFloat(parts[7]) : 0,
      Label: parseInt(parts[parts.length - 1], 10) || 0
    };

    if (!isNaN(record.Value_0h) && !isNaN(record.Value_24h)) {
      records.push(record);
    }
  }

  return records;
}

// Generate the complete 1000-component benchmark dataset
export function getBenchmarkDataset(): RawComponentRecord[] {
  // We parse the exact CSV provided in the prompt
  return parseCsvDataset(RAW_CSV_TEXT);
}
